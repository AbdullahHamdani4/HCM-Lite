import { Document, Page, Text, View, StyleSheet, renderToBuffer } from "@react-pdf/renderer";

const pkr = (n) => "PKR " + Number(n || 0).toLocaleString("en-PK", { maximumFractionDigits: 0 });

const s = StyleSheet.create({
  page: { padding: 40, fontSize: 10, fontFamily: "Helvetica", color: "#0A0A0A" },
  head: { flexDirection: "row", justifyContent: "space-between", borderBottom: "1 solid #E4E4E7", paddingBottom: 16, marginBottom: 20 },
  company: { fontSize: 16, fontFamily: "Helvetica-Bold" },
  muted: { color: "#71717A" },
  accent: { width: 24, height: 3, backgroundColor: "#FF4F00", marginBottom: 8 },
  grid: { flexDirection: "row", gap: 24, marginBottom: 20 },
  col: { flex: 1 },
  label: { color: "#71717A", fontSize: 8, textTransform: "uppercase", letterSpacing: 0.6, marginBottom: 2 },
  row: { flexDirection: "row", justifyContent: "space-between", paddingVertical: 6, borderBottom: "1 solid #F4F4F5" },
  h: { fontFamily: "Helvetica-Bold", fontSize: 11, marginBottom: 6, marginTop: 8 },
  net: { flexDirection: "row", justifyContent: "space-between", marginTop: 20, padding: 14, border: "1 solid #0A0A0A" },
  netAmt: { fontSize: 18, fontFamily: "Helvetica-Bold" },
});

function Line({ k, v }) {
  return (
    <View style={s.row}>
      <Text style={s.muted}>{k}</Text>
      <Text>{v}</Text>
    </View>
  );
}

function Slip({ p, company, dept }) {
  return (
    <Document>
      <Page size="A4" style={s.page}>
        <View style={s.head}>
          <View>
            <View style={s.accent} />
            <Text style={s.company}>{company}</Text>
            <Text style={s.muted}>Payslip · {p.month}</Text>
          </View>
          <View style={{ alignItems: "flex-end" }}>
            <Text style={s.label}>Status</Text>
            <Text>{p.status === "finalized" ? "Finalized" : "Draft"}</Text>
          </View>
        </View>
        <View style={s.grid}>
          {[["Employee", p.name], ["Code", p.code], ["Department", dept || "—"], ["Working days", `${p.employedDays} / ${p.workingDays}`]].map(([k, v]) => (
            <View key={k} style={s.col}>
              <Text style={s.label}>{k}</Text>
              <Text>{v}</Text>
            </View>
          ))}
        </View>
        <View style={s.grid}>
          <View style={s.col}>
            <Text style={s.h}>Earnings</Text>
            <Line k="Basic" v={pkr(p.basic)} />
            <Line k="House rent (40%)" v={pkr(p.hra)} />
            <Line k="Medical (10%)" v={pkr(p.medical)} />
            <Line k="Gross" v={pkr(p.gross)} />
            {p.employedDays < p.workingDays && <Line k="Prorated gross" v={pkr(p.proratedGross)} />}
          </View>
          <View style={s.col}>
            <Text style={s.h}>Deductions</Text>
            <Line k={`Absent (${p.absent} d)`} v={pkr(p.perDay * p.absent)} />
            <Line k={`Unpaid leave (${p.unpaid} d)`} v={pkr(p.perDay * p.unpaid)} />
            <Line k={`Half days (${p.halfDays} × 0.5)`} v={pkr(p.perDay * p.halfDays * 0.5)} />
            <Line k="Income tax" v={pkr(p.tax)} />
          </View>
        </View>
        <View style={s.net}>
          <Text>Net pay</Text>
          <Text style={s.netAmt}>{pkr(p.net)}</Text>
        </View>
        <Text style={[s.muted, { marginTop: 24, fontSize: 8 }]}>
          Per-day rate {pkr(p.perDay)}. Tax slab is illustrative. Generated by HCM Lite.
        </Text>
      </Page>
    </Document>
  );
}

export const renderPayslip = (p, company, dept) => renderToBuffer(<Slip p={p} company={company} dept={dept} />);
